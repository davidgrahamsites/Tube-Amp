"""Two illustrated reader pages for the actual-size Fischer cabinet fit kit."""
import pymupdf as pdf


def add_guide(doc, fit, p, drawing):
    mm, point, line, label, rect, ink, teal, grey = drawing
    def page(number, title, subtitle):
        sheet=doc.new_page(width=210*mm,height=297*mm)
        label(sheet,14,16,'RENEGADE   /   CABINET FIT GUIDE',10,True,teal)
        label(sheet,14,31,title,24,True)
        label(sheet,14,41,subtitle,11)
        line(sheet,14,47,196,47,grey)
        line(sheet,14,276,196,276,grey)
        label(sheet,14,284,'CB-010    /    PA340 effects return    /    November 2026',9)
        label(sheet,184,284,f'{number} / 5',9)
        return sheet
    def fill(sheet,x,y,w,h,colour):
        sheet.draw_rect(pdf.Rect(point(x,y),point(x+w,y+h)),color=ink,fill=colour,width=.7)

    a=page(1,'Why this paper kit exists','A cardboard stand-in for a cooling assembly inside the guitar amplifier.')
    label(a,14,59,'What is a Fischer heatsink?',15,True)
    label(a,14,68,'Fischer Elektronik makes the SK 81 50 SA, a finned aluminium part. The PA340 chip')
    label(a,14,74,'drives the effects-return signal and gives off heat. A spreader carries that heat to the')
    label(a,14,80,'fins. Air moving between the fins carries heat away. A guard surrounds the fins.')
    label(a,14,92,'Where would it go?',15,True)
    label(a,14,101,'Near the top of the cabinet, above the speaker. The sink attaches to the back wall of')
    label(a,14,107,'the removable metal electronics tray. Its fins face the removable wooden rear cover.')

    label(a,17,123,'FRONT',9,True,teal)
    label(a,159,123,'REAR',9,True,teal)
    fill(a,26,130,145,4,(.86,.73,.54))
    fill(a,26,134,5,47,(.86,.73,.54))
    fill(a,166,134,5,47,(.86,.73,.54))
    fill(a,35,139,93,22,(.85,.89,.91))
    fill(a,128,141,3,16,(.42,.49,.53))
    for fy in (141,145,149,153,156):
        fill(a,131,fy,12,1,(.42,.49,.53))
    rect(a,128,139,21,22,teal)
    label(a,43,151,'Metal tray',10,True)
    label(a,15,194,'Speaker board',9,True)
    line(a,28,182,28,188)
    label(a,94,194,'Fins and guard',9,True)
    line(a,139,162,123,184,teal)
    label(a,157,194,'Rear cover',9,True)
    line(a,169,182,169,188)
    label(a,49,174,'Side view above the speaker. Diagram shows the proposed location.',8)
    label(a,14,209,'Why a recess?',15,True)
    label(a,14,218,f'The measured space between the two wooden faces was about {fit["measured_approx_mm"]} mm. With a flat tray')
    label(a,14,224,'the guard would overlap the wood by about 3 mm. A 15 mm step in the metal tray')
    label(a,14,230,'moves the fins forward. The model predicts about 12 mm of clearance at that location.')
    label(a,14,243,'The paper check',12,True)
    label(a,14,251,'The kit lets you feel whether the full-width assembly fits with at least 5 mm to spare,')
    label(a,14,257,'including near screws and wooden strips. It also checks whether the cover can come off.')
    label(a,14,263,'The paper pieces are for an empty, unpowered cabinet. Cooling needs a later heat test.')

    b=page(2,'Materials and assembly','Read this page first. Pages 3, 4 and 5 contain the full-size patterns.')
    label(b,14,59,'For the paper fit check',15,True)
    label(b,14,69,'Bring an A4 printer, three sheets of stiff, thin card, clear tape, scissors, a')
    label(b,14,75,'pencil and a metric ruler. If printing on ordinary paper, glue it flat to thin card before')
    label(b,14,81,'cutting. Bring the cabinet, its upper rear cover, its original screws and their screwdriver.')
    label(b,14,91,'Print pages 3-5 single-sided at 100% or Actual Size. On each page measure the')
    label(b,14,97,'100 mm horizontal bar and the 200 mm vertical bar. Correct scaling before cutting.')
    label(b,14,109,'What the paper pieces represent',15,True)
    label(b,14,120,'Page 3   Stepped tray wall',11,True)
    label(b,14,127,'The centre rectangle is the rear face of the pocket. Fold its side strips toward the')
    label(b,14,133,'cover. Their tips show where the flat tray wall would have been.')
    label(b,14,143,'Page 4   Cooling assembly',11,True)
    label(b,14,150,'Fold the cross into a shallow box and tape its four corners. The box represents the')
    label(b,14,156,'space taken by the bracket, fins and guard together. Tape its open end to page 3.')
    label(b,14,166,'Page 5   Two measuring strips',11,True)
    label(b,14,173,'The shorter strip sets the tray position. The longer strip includes the guard and the')
    label(b,14,179,'required 5 mm air gap. Use both as shown on page 5. Record the smallest gap.')
    label(b,14,192,'Parts represented in the proposed amplifier',15,True)
    label(b,14,202,'One PA340CC on a small circuit board, a heat spreader and an insulating thermal')
    label(b,14,208,'interface conduct heat to the Fischer aluminium sink (100 x 50 x 15 mm nominal).')
    label(b,14,217,'A metal bracket and clamps hold the assembly on the recessed tray. The depth model')
    label(b,14,223,f'uses a {p["wall_bracket"]:g} mm bracket, {p["guard_air_gap"]:g} mm from fins to guard, and {p["guard_material"]:g} mm guard material. Keep the fins vertical.')
    label(b,14,232,'Fixed cabinet supports carry the tray. The rear cover keeps its own screws. The card')
    label(b,14,238,'kit needs no electronic parts. Leave all wood, mounting holes and wiring as they are.')
    label(b,14,250,'A fit passes when the assembled guard has at least 5 mm clearance everywhere,',10,True)
    label(b,14,256,'the cover and tray can withdraw freely, and the two rear slots remain usable.',10,True)
    label(b,14,265,'Use a folded scrap of paper as a contact witness. Tape it to the card, clear of the wood.',9)
