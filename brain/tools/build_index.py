#!/usr/bin/env python3
"""Generate a small catalog from the engineering brain's Markdown metadata."""
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {'rule-set', 'decision', 'component', 'validation'}
DOMAINS = {'schematic', 'bom', 'components', 'pcb', 'manufacture', 'cross-domain'}
STATUSES = {'documented', 'proposed', 'selected', 'verified', 'blocked', 'superseded'}


def metadata(path):
    lines = path.read_text().splitlines()
    if not lines or lines[0] != '---':
        raise ValueError(f'{path}: missing frontmatter')
    end = lines.index('---', 1)
    fields = dict(line.split(':', 1) for line in lines[1:end] if line.strip())
    fields = {key.strip(): value.strip() for key, value in fields.items()}
    for key in ('id', 'type', 'domain', 'status', 'updated'):
        if not fields.get(key):
            raise ValueError(f'{path}: missing {key}')
    for key, allowed in [('type', TYPES), ('domain', DOMAINS), ('status', STATUSES)]:
        if fields[key] not in allowed:
            raise ValueError(f'{path}: invalid {key}: {fields[key]}')
    date.fromisoformat(fields['updated'])
    fields['title'] = next(line[2:] for line in lines[end + 1:] if line.startswith('# '))
    return fields


def main():
    nodes = []
    seen = set()
    for folder in ('rules', 'records'):
        for path in sorted((ROOT / folder).glob('*.md')):
            if path.name == 'CONTEXT.md':
                continue
            fields = metadata(path)
            if fields['id'] in seen:
                raise ValueError(f'Duplicate ID: {fields["id"]}')
            seen.add(fields['id'])
            nodes.append((fields, path.relative_to(ROOT).as_posix()))
    lines = [
        '# Engineering brain catalog', '',
        'Generated by `tools/build_index.py`; edit the source records, then regenerate.', '',
        'Start with [the brain contract](CONTEXT.md). Evidence is linked in each record.', '',
        '| ID | Type | Domain | Status | Updated | Record |',
        '|---|---|---|---|---|---|',
    ]
    for fields, path in nodes:
        cells = [fields[key] for key in ('id', 'type', 'domain', 'status', 'updated')]
        title = fields['title'].replace('|', '\\|')
        cells.append(f'[{title}]({path})')
        lines.append('| ' + ' | '.join(cells) + ' |')
    (ROOT / 'INDEX.md').write_text('\n'.join(lines) + '\n')
    print(f'Catalog generated: {len(nodes)} nodes; metadata and IDs valid.')


if __name__ == '__main__':
    main()
